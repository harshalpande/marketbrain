#requires -Version 7.5
param([switch]$Check)
$ErrorActionPreference='Stop'
$tokens=$null;$errors=$null
$ast=[Management.Automation.Language.Parser]::ParseFile((Join-Path $PSScriptRoot 'jobs/PaytmTransport.ps1'),[ref]$tokens,[ref]$errors)
if($errors.Count){throw 'Source parser errors'}
$parts=@("#requires -Version 7.5`n# Generated by Build-DenialRecoveryJob.ps1; do not edit directly.`nparam([Parameter(Mandatory)][string]`$ResultPath,[ValidateSet('Observe','Apply','FailureFixture')][string]`$Mode='Observe')`n`$ErrorActionPreference='Stop'")
foreach($name in @('Read-BoundedJson','Get-DenialRecoveryPreflight')){
    $fn=$ast.Find({param($n)$n -is [Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq $name},$true)
    if(-not $fn){throw "Missing $name"};$parts+=$fn.Extent.Text
}
$receipt=Get-Content (Join-Path $PSScriptRoot '../../docs/evidence/queued-recovery-preflight-20261120.json') -Raw|ConvertFrom-Json -AsHashtable -DateKind String
$text=$receipt.result.evidence.recoveryPreflight|ConvertTo-Json -Depth 8 -Compress
$parts+=('$acceptedRecoveryReceipt = @'+"'`n"+$text+"`n'@ | ConvertFrom-Json -AsHashtable -DateKind String")
foreach($name in @('DenialRecovery.Core.ps1','PostRecovery.Core.ps1','DenialRecovery.Entry.ps1')){$parts+=[IO.File]::ReadAllText((Join-Path $PSScriptRoot $name))}
$built=(($parts -join "`n`n").Replace("`r`n","`n")).TrimEnd()+"`n"
$path=Join-Path $PSScriptRoot 'jobs/PaytmDenialRecovery.ps1'
if($Check){if([IO.File]::ReadAllText($path).Replace("`r`n","`n") -cne $built){throw 'Generated recovery job out of date'}}
else{[IO.File]::WriteAllText($path,$built,[Text.UTF8Encoding]::new($false))}
if([Text.Encoding]::UTF8.GetByteCount($built) -gt 65536){throw 'Generated job exceeds catalogue limit'}
Write-Host 'RECOVERY_JOB_BUILD_VERIFIED'
